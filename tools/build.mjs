// Builds every output in build/ from the token sources in tokens/.
//
//   node tools/build.mjs           write the outputs
//   node tools/build.mjs --check   fail if an output on disk differs from what the tokens produce
//
// Style Dictionary reads and resolves the tokens; the files themselves are written here, because
// one CSS file has to carry the palette, a light theme and a dark theme declared twice (for the
// system preference and for an explicit choice), which no built-in format does.

import StyleDictionary from 'style-dictionary';
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');

const BASE = ['color', 'typography', 'shape', 'layout', 'motion'].map((f) => `tokens/${f}.json`);
const HEADER = 'Generated by tools/build.mjs from tokens/. Do not edit by hand.';

// CSS custom property names. Colours drop the "color" prefix and glue a numeric step to its
// scale (color.brand.sand -> --brand-sand, color.plum.800 -> --plum800). Roles, fonts, layout and
// shape drop their group name (role.bg -> --bg, shape.radius.l -> --radius-l). Everything else
// keeps its full path (type.h1.size -> --type-h1-size).
const SHORT = new Set(['font', 'role', 'layout', 'shape']);
StyleDictionary.registerTransform({
  name: 'konta/name',
  type: 'name',
  transform: (token) => {
    const [group, ...rest] = token.path;
    if (group === 'color') return rest.join('-').replace(/-(\d+)$/, '$1');
    if (SHORT.has(group)) return rest.join('-');
    return token.path.join('-');
  },
});

async function load(source, include = []) {
  const sd = new StyleDictionary({
    source: source.map((f) => join(root, f)),
    include: include.map((f) => join(root, f)),
    log: { verbosity: 'silent', warnings: 'disabled' },
    platforms: { css: { transforms: ['konta/name', 'fontFamily/css', 'cubicBezier/css'] } },
  });
  const { allTokens } = await sd.getPlatformTokens('css');
  return allTokens.filter((t) => t.isSource);
}

const base = await load(BASE);
const byPath = new Map(base.map((t) => [t.path.join('.'), t]));

const theme = async (name) => load([`tokens/themes/${name}.json`], BASE);
const site = { light: await theme('site-light'), dark: await theme('site-dark') };
const app = { light: await theme('app-light'), dark: await theme('app-dark') };

// A token that points at another one is written as var(--that-one), so the palette stays the
// single place a colour value lives.
function cssValue(token) {
  const original = token.original.$value ?? token.original.value;
  if (typeof original === 'string') {
    const ref = /^\{([^}]+)\}$/.exec(original);
    if (ref) {
      const target = byPath.get(ref[1]);
      if (!target) throw new Error(`${token.path.join('.')} points at unknown token ${ref[1]}`);
      return `var(--${target.name})`;
    }
  }
  return token.$value ?? token.value;
}

const resolved = (token) => token.$value ?? token.value;
const decls = (tokens, indent) => tokens.map((t) => `${indent}--${t.name}: ${cssValue(t)};`).join('\n');

// One comment per group in the output: "color brand", "color p", "type", "shape"...
function groupLabel(token) {
  const [group, second] = token.path;
  return group === 'color' ? `color ${second}` : group;
}

function baseBlock() {
  const lines = [];
  let last;
  for (const t of base) {
    const label = groupLabel(t);
    if (label !== last) {
      lines.push(`${lines.length ? '\n' : ''}  /* ${label} */`);
      last = label;
    }
    lines.push(`  --${t.name}: ${cssValue(t)};`);
  }
  return `:root {\n${lines.join('\n')}\n}`;
}

function themedCss(pair, intro) {
  if (!pair.light.length && !pair.dark.length) return `/* ${intro}: none defined yet */`;
  return [
    `/* ${intro} */`,
    `:root {\n${decls(pair.light, '  ')}\n  color-scheme: light;\n}`,
    `@media (prefers-color-scheme: dark) {\n  :root:not([data-theme='light']) {\n${decls(pair.dark, '    ')}\n    color-scheme: dark;\n  }\n}`,
    `:root[data-theme='dark'] {\n${decls(pair.dark, '  ')}\n  color-scheme: dark;\n}`,
  ].join('\n\n');
}

const siteCss = [
  `/* ${HEADER}\n   Konta design tokens: the palette, type, shape, layout and motion, then the site's light\n   and dark roles. Dark applies with the system preference unless data-theme='light' is set\n   on <html>, and always with data-theme='dark'. */`,
  baseBlock(),
  themedCss(site, 'Site roles'),
].join('\n\n') + '\n';

const appCss = [
  `/* ${HEADER}\n   App (app.konta.md) overrides. Load after konta-tokens.css. */`,
  themedCss(app, 'App roles'),
].join('\n\n') + '\n';

// Flat, resolved values for anything that is not CSS: the TypeScript app, scripts, and later
// the iOS and Android builds.
const flat = (tokens) => Object.fromEntries(tokens.map((t) => [t.name, resolved(t)]));
const data = {
  base: flat(base),
  site: { light: flat(site.light), dark: flat(site.dark) },
  app: { light: { ...flat(site.light), ...flat(app.light) }, dark: { ...flat(site.dark), ...flat(app.dark) } },
};
const json = JSON.stringify(data, null, 2) + '\n';
const ts = `// ${HEADER}\n// Resolved token values. The app's roles already include the site roles they extend.\n\n` +
  `export const base = ${JSON.stringify(data.base, null, 2)} as const;\n\n` +
  `export const site = ${JSON.stringify(data.site, null, 2)} as const;\n\n` +
  `export const app = ${JSON.stringify(data.app, null, 2)} as const;\n\n` +
  `export type Theme = 'light' | 'dark';\nexport type Role = keyof typeof site.light;\n`;

const outputs = {
  'build/css/konta-tokens.css': siteCss,
  'build/css/konta-tokens-app.css': appCss,
  'build/json/tokens.json': json,
  'build/ts/tokens.ts': ts,
};

let stale = 0;
for (const [file, content] of Object.entries(outputs)) {
  const path = join(root, file);
  if (check) {
    const current = existsSync(path) ? readFileSync(path, 'utf8') : null;
    if (current !== content) {
      console.error(`out of date: ${file} (run npm run build)`);
      stale++;
    }
  } else {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
    console.log(`wrote ${file}`);
  }
}
if (check) {
  if (stale) process.exit(1);
  console.log('build/ matches tokens/');
}
